def new_canvas(w, h):
    img = Image.new("RGB", (w, h), "white")
    return img, ImageDraw.Draw(img)


def box(draw, xy, title, lines, fw=28):
    x1, y1, x2, y2 = xy
    draw.rectangle(xy, outline="black", width=2)
    draw.line((x1, y1 + 42, x2, y1 + 42), fill="black", width=2)
    draw.text((x1 + 12, y1 + 8), title, fill="black", font=font(fw, True))
    y = y1 + 52
    for line in lines:
        draw.text((x1 + 12, y), line, fill="black", font=font(22))
        y += 28


